// Мягкое ограничение частоты на тёплом экземпляре функции. Для защиты на уровне всего сайта
// дополнительно используйте лимиты расходов и защиту от ботов в настройках платформы.
const requestBuckets = new Map();
const isRateLimited = request => {
  const ip = request.headers.get("x-nf-client-connection-ip") || request.headers.get("x-forwarded-for")?.split(",")[0]?.trim();
  if (!ip) return false;
  const now = Date.now();
  const windowMs = 60_000;
  const bucket = requestBuckets.get(ip);
  if (!bucket || now - bucket.startedAt >= windowMs) {
    requestBuckets.set(ip, { startedAt: now, count: 1 });
    return false;
  }
  bucket.count += 1;
  return bucket.count > 18;
};

const json = (data, status = 200) => new Response(JSON.stringify(data), {
  status,
  headers: { "Content-Type": "application/json; charset=utf-8", "Cache-Control": "no-store" }
});

export default async (request) => {
  if (request.method !== "POST") return json({ error: "Method not allowed" }, 405);
  if (isRateLimited(request)) return json({ error: "Слишком много сообщений за короткое время. Сделайте небольшую паузу." }, 429);

  const apiKey = process.env.OPENAI_API_KEY;
  if (!apiKey) {
    return json({
      code: "AI_NOT_CONFIGURED",
      error: "ИИ не настроен. Добавьте OPENAI_API_KEY в переменные окружения Netlify."
    }, 503);
  }

  let payload;
  try {
    const raw = await request.text();
    if (raw.length > 16000) return json({ error: "Слишком большое сообщение." }, 413);
    payload = JSON.parse(raw);
  } catch {
    return json({ error: "Не удалось прочитать сообщение." }, 400);
  }

  const message = typeof payload?.message === "string" ? payload.message.trim() : "";
  if (!message) return json({ error: "Введите вопрос." }, 400);
  if (message.length > 1000) return json({ error: "Сообщение слишком длинное. Сократите его до 1000 символов." }, 400);

  const history = Array.isArray(payload.history) ? payload.history.slice(-8) : [];
  const safeHistory = history
    .filter(item => item && ["user", "assistant"].includes(item.role) && typeof item.content === "string")
    .map(item => ({ role: item.role, content: item.content.slice(0, 1000) }));
  safeHistory.push({ role: "user", content: message });

  try {
    const apiResponse = await fetch("https://api.openai.com/v1/responses", {
      method: "POST",
      headers: {
        "Authorization": `Bearer ${apiKey}`,
        "Content-Type": "application/json"
      },
      body: JSON.stringify({
        model: process.env.OPENAI_MODEL || "gpt-5.5",
        instructions: COMPANY_CONTEXT,
        input: safeHistory,
        max_output_tokens: 450,
        store: false
      })
    });

    const result = await apiResponse.json().catch(() => ({}));
    if (!apiResponse.ok) {
      console.error("OpenAI API response error:", apiResponse.status, result?.error?.code || "unknown");
      return json({ error: "Сейчас ИИ-консультант временно недоступен. Попробуйте позже или позвоните менеджеру." }, apiResponse.status === 429 ? 429 : 502);
    }

    const reply = (result.output || [])
      .filter(item => item.type === "message")
      .flatMap(item => item.content || [])
      .filter(item => item.type === "output_text" && typeof item.text === "string")
      .map(item => item.text)
      .join("\n")
      .trim();

    if (!reply) return json({ error: "Не удалось получить текстовый ответ." }, 502);
    return json({ reply });
  } catch (error) {
    console.error("Chat function error:", error?.message || "unknown error");
    return json({ error: "Не удалось связаться с ИИ-сервисом. Попробуйте позже." }, 502);
  }
};
